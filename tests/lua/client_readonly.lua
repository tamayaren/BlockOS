-- A second client paired read-only: may browse and download, may not change anything.
local T = dofile("/tests/testlib.lua")

T.Run(function()
	local Client = BlockOS.Require("cloud/client")
	local Drive = BlockOS.Require("cloud/drive")
	sleep(4)
	local Nodes = Client.Discover(2)
	local Session = Client.StartPairing(Nodes[1], "Lobby Kiosk")
	T.Check("read-only: pairing requested", Session ~= nil)
	sleep(1)
	local Approval = T.Admin(1, { Op = "approve", Code = Session.Code, Permission = "read" })
	T.Check("read-only: approved", Approval and Approval.Ok, Approval and Approval.Err)
	local Server = Client.WaitPairing(Session, nil, 30)
	T.Check("read-only: paired with read permission", Server and Server.Permission == "read")
	T.Check("read-only: can list", Drive.List(Server, "Shared") ~= nil)
	local R, E = Drive.WriteText(Server, "Shared/kiosk.txt", "hi")
	T.ExpectError("read-only: upload denied", "denied", R, E)
	R, E = Drive.MakeDir(Server, "Shared/kiosk")
	T.ExpectError("read-only: mkdir denied", "denied", R, E)
	R, E = Drive.Delete(Server, "Shared/blob.bin")
	T.ExpectError("read-only: delete denied", "denied", R, E)
end)
