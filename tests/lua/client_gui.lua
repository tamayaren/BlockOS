-- BlockDrive inside the real BlockOS desktop, driven like a player would: pair with the Data
-- Center, upload a document from the file picker, open it in the editor, change it and save.
local T = dofile("/tests/testlib.lua")
local D = dofile("/tests/driver.lua")

local function Test()
	local Ready = D.Wait("No servers yet", 40)
	T.Check("gui: BlockDrive opens on the desktop", Ready ~= nil)
	D.Dump("/screens.txt")
	local X, Y = D.Wait("Add Server")
	D.Click(X, Y)
	X, Y = D.Wait("Data Center (datacenter)", 10)
	T.Check("gui: finds the Data Center", X ~= nil)
	D.Click(X, Y)
	X, Y = D.Wait(" Pair ", 5, true)
	D.Click(X + 1, Y)
	X, Y = D.Wait("Name for this computer", 5)
	T.Check("gui: asks for a computer name", X ~= nil)
	D.Key(keys.enter)
	D.Wait("type this code", 10)
	D.Dump("/screens.txt")
	local Code = D.Match(" (%w%w%w%w%-%w%w%w%w) ")
	T.Check("gui: shows a pairing code", Code ~= nil, Code)
	local Approval = T.Admin(1, { Op = "approve", Code = Code, Permission = "write" })
	T.Check("gui: administrator approves the code", Approval and Approval.Ok, Approval and Approval.Err)
	T.Check("gui: pairing completes", D.Wait("Paired with Data Center", 15) ~= nil)
	X, Y = D.Wait("Shared", 10)
	D.DoubleClick(X, Y)
	X, Y = D.Wait("This folder is empty", 10)
	T.Check("gui: opens the Shared share", X ~= nil)
	D.Dump("/screens.txt")
	D.Click(X, Y, 2)
	X, Y = D.Wait("Upload File...", 5)
	D.Click(X, Y)
	X, Y = D.Wait("report.txt", 5)
	T.Check("gui: file picker shows local files", X ~= nil)
	D.Click(X, Y)
	X, Y = D.Wait("Open", 5, true)
	D.Click(X, Y)
	T.Check("gui: upload finishes", D.Wait("Uploaded report.txt", 20) ~= nil)
	D.Dump("/screens.txt")
	X, Y = D.Wait("report.txt", 5)
	D.DoubleClick(X, Y)
	T.Check("gui: opens the remote file in the editor", D.Wait("Ctrl+S saves", 15) ~= nil)
	T.Check("gui: editor shows the remote text", D.Wait("Revenue: 64 diamonds", 5) ~= nil)
	D.Type("Edited! ")
	D.Key(keys.s, true)
	T.Check("gui: save reports success", D.Wait("Saved report.txt", 15) ~= nil)
	D.Dump("/screens.txt")
	local Client = BlockOS.Require("cloud/client")
	local Drive = BlockOS.Require("cloud/drive")
	local Server = Client.List()[1]
	local Text = Server and Drive.ReadText(Server, "Shared/report.txt")
	T.Check("gui: saved text is on the server", Text and Text:sub(1, 8) == "Edited! " and Text:find("64 diamonds", 1, true), Text)
	X, Y = D.Wait("Files", 5)
	D.Click(X, Y)
	T.Check("gui: back to the file list", D.Wait("report.txt", 10) ~= nil)
	T.Check("gui: share stays in the sidebar", D.Wait(" Shared", 5) ~= nil)
	D.Dump("/screens.txt")
end

T.WriteFile("/home/report.txt", "Quarterly report\nRevenue: 64 diamonds\n")
parallel.waitForAny(function()
	shell.run("/blockos/boot.lua")
end, function()
	T.Run(Test)
	sleep(60)
end)
