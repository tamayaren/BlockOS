-- On a desktop built from the main branch: get BlockDrive from the App Store, open it, and pair
-- with the Data Center through its window.
local T = dofile("/tests/testlib.lua")
local D = dofile("/tests/driver.lua")

local function Test()
	local X, Y = D.Wait("BlockDrive", 40)
	T.Check("store: BlockDrive listed in the App Store", X ~= nil)
	D.Dump("/screens.txt")
	D.DoubleClick(X, Y)
	X, Y = D.Wait("OPEN", 20)
	T.Check("store: installs", X ~= nil and fs.exists("/blockos/userapps/blockdrive/main.lua"))
	D.Dump("/screens.txt")
	-- Double-click the list row (now marked OPEN), not the "ready" notification.
	D.DoubleClick(X - 6, Y)
	T.Check("store: app opens", D.Wait("No servers yet", 20) ~= nil)
	T.Check("store: client library installed", fs.exists("/blockos/lib/cloud/client.lua") and fs.exists("/blockos/bin/bdrive.lua")
		and BlockOS.Require("config").ReadText("/blockos/lib/cloud/version.txt") == "1.0.0")
	X, Y = D.Wait("Add Server")
	D.Click(X, Y)
	X, Y = D.Wait("Data Center (datacenter)", 10)
	D.Click(X, Y)
	X, Y = D.Wait(" Pair ", 5, true)
	D.Click(X + 1, Y)
	D.Wait("Name for this computer", 5)
	D.Key(keys.enter)
	D.Wait("type this code", 10)
	local Code = D.Match(" (%w%w%w%w%-%w%w%w%w) ")
	local Approval = T.Admin(1, { Op = "approve", Code = Code, Permission = "write" })
	T.Check("store: pairing approved", Approval and Approval.Ok, Approval and Approval.Err)
	T.Check("store: browses the Data Center", D.Wait("Shared", 15) ~= nil)
	D.Dump("/screens.txt")
	local Info = BlockOS.Require("cloud/drive").Info(BlockOS.Require("cloud/client").List()[1])
	T.Check("store: library works for other apps too", Info and Info.Shares[1] == "Shared")
end

parallel.waitForAny(function()
	shell.run("/blockos/boot.lua")
end, function()
	T.Run(Test)
	sleep(60)
end)
