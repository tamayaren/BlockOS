-- App Store: browses repository catalogs, installs apps from Pastebin or URLs,
-- and manages installed apps.

local Ui = BlockOS.Require("ui")
local Gfx = BlockOS.Require("gfx")
local Apps = BlockOS.Require("apps")
local Config = BlockOS.Require("config")
local Updater = BlockOS.Require("updater")

local Page = Ui.Page.new()
local Tab = 1
local Catalog = {}
local Loading = false
local Status = ""
local Query = ""
local Selected = nil
local Form = { Code = "", Name = "", Icon = "", Color = 1, Fullscreen = false }
local IconColors = { "blue", "purple", "magenta", "red", "orange", "yellow", "lime", "green", "cyan", "lightBlue", "pink", "gray", "black" }

local function Installed()
	local Result = {}
	for _, App in ipairs(Apps.List(true)) do
		if (not App.System) then
			Result[App.StoreID or App.ID] = App
		end
	end
	return Result
end

local function ResolveUrl(Base, Url)
	if (Url:match("^https?://")) then return Url end
	return Base:gsub("[^/]*$", "") .. Url
end

local function FetchCatalogs()
	Loading = true
	Catalog = {}
	Status = "Loading catalogs..."
	Page:Draw()
	local Errors = 0
	for _, Url in ipairs(Config.Settings().Repositories) do
		local Body = Updater.Get(Url)
		local Data = Body and textutils.unserialise(Body)
		if (type(Data) == "table" and type(Data.Apps) == "table") then
			for _, Entry in ipairs(Data.Apps) do
				if (type(Entry) == "table" and Entry.ID and Entry.Name and type(Entry.Source) == "table") then
					Entry.Repository = Data.Name or Url
					Entry.Base = Url
					table.insert(Catalog, Entry)
				end
			end
		else
			Errors = Errors + 1
		end
	end
	table.sort(Catalog, function(A, B) return A.Name:lower() < B.Name:lower() end)
	Loading = false
	Status = #Catalog .. " apps" .. (Errors > 0 and (", " .. Errors .. " source(s) unavailable") or "")
end

local function DownloadSource(Entry)
	local Source = Entry.Source
	if (Source.Type == "pastebin") then
		return Apps.FetchPastebin(Source.Code)
	elseif (Source.Type == "url") then
		return Apps.Fetch(ResolveUrl(Entry.Base or "", Source.Url))
	elseif (Source.Type == "rom") then
		return "-- Launcher generated by the App Store\nshell.run(" .. string.format("%q", Source.Program) .. ", ...)\n"
	end
	return nil, "Unknown source type"
end

local function InstallEntry(Entry)
	Status = "Downloading " .. Entry.Name .. "..."
	Page:Draw()
	local Source, Err = DownloadSource(Entry)
	if (not Source) then
		Status = ""
		Ui.Alert("Install failed", tostring(Err))
		return
	end
	local Ok, CompileErr = load(Source, "=" .. Entry.ID)
	if (not Ok and not Ui.Confirm("Warning", "This app has a syntax error and may not run:\n" .. tostring(CompileErr), "Install Anyway")) then
		Status = ""
		return
	end
	local Existing = Installed()[Entry.ID]
	Apps.Install({
		ID = Existing and Existing.ID or Entry.ID,
		Name = Entry.Name,
		Description = Entry.Description,
		Author = Entry.Author,
		Category = Entry.Category,
		Version = Entry.Version,
		StoreID = Entry.ID,
		Mode = Entry.Mode,
		Width = Entry.Width,
		Height = Entry.Height,
		Icon = Entry.Icon,
		Source = Entry.Source
	}, Source)
	Status = Entry.Name .. " installed"
	BlockOS.Notify("App Store", Entry.Name .. " is ready in Launchpad.", { AppID = "appstore", Sound = false })
end

local function Filtered()
	local Result = {}
	local Needle = Query:lower()
	for _, Entry in ipairs(Catalog) do
		if (Needle == "" or Entry.Name:lower():find(Needle, 1, true) or (Entry.Category or ""):lower():find(Needle, 1, true)) then
			table.insert(Result, Entry)
		end
	end
	return Result
end

local Build

local function Header(W)
	local TabsW = math.min(W - 2, 44)
	Page:Add(Ui.Tabs.new({
		X = math.floor((W - TabsW) / 2) + 1, Y = 1, W = TabsW, Items = { "Discover", "Installed", "Pastebin", "Sources" }, Selected = Tab,
		OnChange = function(_, Index)
			Tab = Index
			Build()
		end
	}))
end

local function BuildDiscover(W, H)
	local ListW = (W >= 40) and math.floor(W * .45) or W
	local Search = Page:Add(Ui.Input.new({ X = 2, Y = 3, W = ListW - 2, Value = Query, Placeholder = "\16 Search apps" }))
	local List = Page:Add(Ui.List.new({ X = 1, Y = 5, W = ListW, H = H - 6 }))
	local Have = Installed()
	local function Fill()
		local Items = {}
		for _, Entry in ipairs(Filtered()) do
			local Mine = Have[Entry.ID]
			local Label = "GET"
			if (Mine) then
				Label = (Entry.Version and Mine.Version and Updater.Compare(Mine.Version, Entry.Version) < 0) and "UPDATE" or "OPEN"
			end
			local Icon = Entry.Icon or Apps.DefaultIcon(Entry.Name)
			table.insert(Items, {
				Text = Entry.Name,
				Icon = Gfx.Pad(Icon.Lines and Icon.Lines[1] or "", 3),
				IconFg = colors[Icon.Bg] or Icon.Bg or colors.gray,
				Right = Label,
				Entry = Entry
			})
		end
		List:SetItems(Items)
		for Index, Item in ipairs(Items) do
			if (Item.Entry == Selected) then List:Select(Index) end
		end
	end
	Search.OnChange = function(_, Value)
		Query = Value
		Fill()
	end
	local function Act(Entry)
		local Mine = Installed()[Entry.ID]
		if (Mine and not (Entry.Version and Mine.Version and Updater.Compare(Mine.Version, Entry.Version) < 0)) then
			BlockOS.Launch(Mine.ID)
		else
			InstallEntry(Entry)
			Build()
		end
	end
	local Action
	local function ActionText()
		local Mine = Selected and Installed()[Selected.ID]
		if (not Mine) then return "Get" end
		if (Selected.Version and Mine.Version and Updater.Compare(Mine.Version, Selected.Version) < 0) then return "Update" end
		return "Open"
	end
	List.OnSelect = function(_, _, Item)
		Selected = Item.Entry
		if (Action) then
			Action.Enabled = true
			Page:Invalidate()
		end
	end
	List.OnActivate = function(_, _, Item)
		if (ListW == W) then
			local Entry = Item.Entry
			local Choice = Ui.Alert(Entry.Name, (Entry.Description or "") .. "\n\nBy " .. (Entry.Author or "unknown"), { "Close", Item.Right == "GET" and "Get" or (Item.Right == "UPDATE" and "Update" or "Open") })
			if (Choice == 2) then Act(Entry) end
		else
			Act(Item.Entry)
		end
	end
	Fill()
	if (ListW < W) then
		local DetailX = ListW + 2
		local DetailW = W - ListW - 2
		Page:Add(Ui.Canvas.new({
			X = DetailX, Y = 3, W = DetailW, H = H - 6,
			OnDraw = function(Self, T, Th)
				local Entry = Selected
				if (not Entry) then
					Gfx.Write(T, Self.X, Self.Y + 1, Gfx.Truncate(Loading and "Loading..." or "Select an app", Self.W), Th.SubText, Th.WindowBg)
					return
				end
				local Icon = Entry.Icon or Apps.DefaultIcon(Entry.Name)
				local Fg = colors[Icon.Fg] or Icon.Fg or colors.white
				local Bg = colors[Icon.Bg] or Icon.Bg or colors.gray
				for Row = 1, 2 do
					Gfx.Write(T, Self.X, Self.Y + Row - 1, Gfx.Pad(Icon.Lines and Icon.Lines[Row] or "", 3), Fg, Bg)
				end
				Gfx.Write(T, Self.X + 4, Self.Y, Gfx.Truncate(Entry.Name, Self.W - 4), Th.Text, Th.WindowBg)
				Gfx.Write(T, Self.X + 4, Self.Y + 1, Gfx.Truncate((Entry.Category or "App") .. " \7 " .. (Entry.Author or "?"), Self.W - 4), Th.SubText, Th.WindowBg)
				local Lines = Gfx.Wrap(Entry.Description or "", Self.W)
				for Row = 1, math.min(#Lines, Self.H - 5) do
					Gfx.Write(T, Self.X, Self.Y + 2 + Row, Lines[Row], Th.Text, Th.WindowBg)
				end
				Gfx.Write(T, Self.X, Self.Y + Self.H - 1, Gfx.Truncate("Version " .. (Entry.Version or "?") .. " from " .. (Entry.Repository or ""), Self.W), Th.SubText, Th.WindowBg)
			end
		}))
		Action = Page:Add(Ui.Button.new({
			X = W - 9, Y = H - 2, W = 8, Text = ActionText, Style = "primary", Enabled = Selected ~= nil,
			OnClick = function()
				if (Selected) then Act(Selected) end
			end
		}))
	end
end

local function BuildInstalled(W, H)
	local List = Page:Add(Ui.List.new({ X = 1, Y = 3, W = W, H = H - 4 }))
	local Items = {}
	for _, App in ipairs(Apps.List(true)) do
		if (not App.System) then
			table.insert(Items, {
				Text = App.Name,
				Icon = Gfx.Pad(App.Icon.Lines[1], 3),
				IconFg = App.Icon.Bg,
				Right = App.Version or "",
				App = App
			})
		end
	end
	if (#Items == 0) then
		Page:Add(Ui.Label.new({ X = 2, Y = 4, W = W - 2, Text = "No apps installed yet.", Fg = "SubText" }))
	end
	List:SetItems(Items)
	local function Menu(Item, X, Y)
		local App = Item.App
		local Pinned = Apps.IsPinned(App.ID)
		local Options = { "Open", "Open Full Screen", Pinned and "Remove from Dock" or "Keep in Dock", "Edit Source", "-", "Uninstall" }
		local Choice = Options[Ui.ContextMenu(X, Y, Options) or 0]
		if (Choice == "Open") then
			BlockOS.Launch(App.ID)
		elseif (Choice == "Open Full Screen") then
			BlockOS.Launch(App.ID, {}, { Mode = "fullscreen" })
		elseif (Choice == "Keep in Dock" or Choice == "Remove from Dock") then
			Apps.SetPinned(App.ID, not Pinned)
		elseif (Choice == "Edit Source") then
			BlockOS.Launch("editor", { App.Path })
		elseif (Choice == "Uninstall") then
			if (Ui.Confirm("Uninstall", "Remove " .. App.Name .. "?", "Uninstall")) then
				Apps.Uninstall(App.ID)
				Build()
			end
		end
	end
	List.OnActivate = function(_, _, Item) BlockOS.Launch(Item.App.ID) end
	List.OnContext = function(_, _, Item, X, Y)
		if (Item) then Menu(Item, X, Y) end
	end
	Page:Add(Ui.Label.new({ X = 2, Y = H - 1, W = W - 2, Text = "Right-click an app for more options.", Fg = "SubText" }))
end

local function BuildPastebin(W, H)
	local FieldW = math.min(W - 16, 28)
	Page:Add(Ui.Label.new({ X = 2, Y = 3, W = W - 2, Text = "Install any program from Pastebin or a URL as an app.", Fg = "SubText" }))
	Page:Add(Ui.Label.new({ X = 2, Y = 5, Text = "Code / URL" }))
	local Code = Page:Add(Ui.Input.new({ X = 14, Y = 5, W = FieldW, Value = Form.Code, Placeholder = "e.g. aBcD1234" }))
	Code.OnChange = function(_, Value) Form.Code = Value end
	Page:Add(Ui.Label.new({ X = 2, Y = 7, Text = "Name" }))
	local Name = Page:Add(Ui.Input.new({ X = 14, Y = 7, W = FieldW, Value = Form.Name, Placeholder = "My App", MaxLength = 24 }))
	Name.OnChange = function(_, Value) Form.Name = Value end
	Page:Add(Ui.Label.new({ X = 2, Y = 9, Text = "Icon" }))
	local Icon = Page:Add(Ui.Input.new({ X = 14, Y = 9, W = 4, Value = Form.Icon, MaxLength = 3 }))
	Icon.OnChange = function(_, Value) Form.Icon = Value end
	Page:Add(Ui.Canvas.new({
		X = 19, Y = 9, W = 3, H = 1,
		OnDraw = function(Self, T)
			local Text = (#Form.Icon > 0) and Form.Icon or Apps.DefaultIcon(Form.Name ~= "" and Form.Name or "App").Lines[1]
			Gfx.Write(T, Self.X, Self.Y, Gfx.Pad(Text, 3), colors.white, colors[IconColors[Form.Color]])
		end,
		OnEvent = function(_, EventName)
			if (EventName ~= "mouse_click") then return false end
			Form.Color = Form.Color % #IconColors + 1
			return true
		end
	}))
	Page:Add(Ui.Label.new({ X = 23, Y = 9, Text = "\27 click for colour", Fg = "SubText" }))
	Page:Add(Ui.Label.new({ X = 2, Y = 11, Text = "Open as" }))
	Page:Add(Ui.Tabs.new({
		X = 14, Y = 11, W = 22, Items = { "Window", "Full Screen" }, Selected = Form.Fullscreen and 2 or 1,
		OnChange = function(_, Index) Form.Fullscreen = Index == 2 end
	}))
	Page:Add(Ui.Button.new({
		X = W - 11, Y = H - 1, W = 10, Text = "Install", Style = "primary",
		OnClick = function()
			local Input = Form.Code:gsub("^%s+", ""):gsub("%s+$", "")
			if (#Input == 0) then
				Ui.Alert("Install", "Enter a Pastebin code or a URL.")
				return
			end
			local AppName = (#Form.Name > 0) and Form.Name or Input:match("([%w_%-]+)%.?%w*$") or "App"
			Status = "Downloading..."
			Page:Draw()
			local Source, Err
			local SourceInfo
			if (Input:match("^https?://") and not Input:match("pastebin%.com")) then
				Source, Err = Apps.Fetch(Input)
				SourceInfo = { Type = "url", Url = Input }
			else
				Source, Err = Apps.FetchPastebin(Input)
				SourceInfo = { Type = "pastebin", Code = Input }
			end
			Status = ""
			if (not Source) then
				Ui.Alert("Install failed", tostring(Err))
				return
			end
			local Lines = (#Form.Icon > 0) and { Gfx.Pad(Form.Icon, 3), "   " } or Apps.DefaultIcon(AppName).Lines
			local App = Apps.Install({
				Name = AppName,
				Description = "Installed from " .. (SourceInfo.Type == "pastebin" and ("Pastebin " .. Input) or Input),
				Mode = Form.Fullscreen and "fullscreen" or "window",
				Icon = { Lines = Lines, Fg = "white", Bg = IconColors[Form.Color] },
				Source = SourceInfo,
				Version = "1.0"
			}, Source)
			Form = { Code = "", Name = "", Icon = "", Color = Form.Color, Fullscreen = false }
			if (App and Ui.Confirm("Installed", AppName .. " was added to Applications. Open it now?", "Open")) then
				BlockOS.Launch(App.ID)
			end
			Build()
		end
	}))
	Page:SetFocus(Code)
end

local function BuildSources(W, H)
	local Settings = Config.Settings()
	local List = Page:Add(Ui.List.new({ X = 1, Y = 3, W = W, H = H - 5 }))
	local Items = {}
	for Index, Url in ipairs(Settings.Repositories) do
		table.insert(Items, { Text = Url, Icon = "\4", IconFg = "Accent", Index = Index })
	end
	List:SetItems(Items)
	Page:Add(Ui.Button.new({
		X = 2, Y = H - 1, Text = " Add Source ",
		OnClick = function()
			local Url = Ui.Prompt("Add Source", "Catalog URL (catalog.cfg):", "https://")
			if (Url and Url:match("^https?://.+")) then
				table.insert(Settings.Repositories, Url)
				Config.Save("settings")
				Build()
			end
		end
	}))
	Page:Add(Ui.Button.new({
		X = 16, Y = H - 1, Text = " Remove ",
		OnClick = function()
			local Item = List.Items[List.Selected]
			if (Item and Ui.Confirm("Remove Source", Item.Text, "Remove")) then
				table.remove(Settings.Repositories, Item.Index)
				Config.Save("settings")
				Build()
			end
		end
	}))
	Page:Add(Ui.Button.new({
		X = W - 10, Y = H - 1, Text = " Reload ", Style = "primary",
		OnClick = function()
			FetchCatalogs()
			Tab = 1
			Build()
		end
	}))
end

function Build()
	Page:Clear()
	local W, H = Page.W, Page.H
	Header(W)
	if (Tab == 1) then
		BuildDiscover(W, H)
	elseif (Tab == 2) then
		BuildInstalled(W, H)
	elseif (Tab == 3) then
		BuildPastebin(W, H)
	else
		BuildSources(W, H)
	end
	Page:Add(Ui.Label.new({ X = 1, Y = H, W = W, Text = function() return Status end, Fg = "SubText", Bg = "Panel", Align = "center" }))
	Page:Invalidate()
end

function Page:OnLayout()
	Build()
end

function Page:OnEvent(Name)
	if (Name == "appstore_refresh") then
		FetchCatalogs()
		Build()
		return true
	elseif (Name == "blockos_apps") then
		if (Tab ~= 3) then Build() end
		return true
	end
	return false
end

os.queueEvent("appstore_refresh")
Page:Run()
